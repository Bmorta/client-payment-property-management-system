import {listMonitoring,waivePenalty,reviewForfeiture,refreshMonitoring} from "../controllers/monitoringController.js";
import { correctPayment, listApprovalRequests, decideCorrection } from "../controllers/paymentCorrectionController.js";
import { listNotifications, readNotifications, streamNotifications } from "../controllers/notificationController.js";
import { searchClients } from "../controllers/clientSearchController.js";
import { auditMutation } from "../middleware/auditMutation.js";
import { Router } from "express";
import { authenticate } from "../middleware/auth.js";
import { authorize } from "../middleware/authorize.js";
import { listAccounts, acceptPayment, listPayments, listExpenses, createExpense, report, updateAgreement, getAccount, previewPayment, exportMonitoringReport, exportPaymentRegister, dashboardAnalytics } from "../controllers/financeController.js";
const router = Router();
router.use(authenticate, auditMutation);
router.get("/monitoring",listMonitoring);
router.post("/accounts/:id/penalties/waive",authorize("ADMIN"),waivePenalty);
router.post("/accounts/:id/forfeiture-review",authorize("ADMIN"),reviewForfeiture);
router.post("/accounts/:id/monitoring/refresh",authorize("ADMIN"),refreshMonitoring);
router.get("/notifications", listNotifications);
router.get("/notifications/stream", streamNotifications);
router.post("/notifications/read-all", readNotifications);
router.post("/notifications/:notificationId/read", readNotifications);
router.get("/approval-requests", authorize("ADMIN","STAFF"), listApprovalRequests);
router.post("/accounts/:id/payments/:paymentId/corrections", authorize("ADMIN","STAFF"), correctPayment);
router.post("/accounts/:id/requests/:requestId/decision", authorize("ADMIN"), decideCorrection);
router.get("/clients/search", searchClients);
router.get("/accounts/:id", getAccount);
router.get("/accounts", listAccounts);
router.patch("/accounts/:id/agreement", authorize("ADMIN"), updateAgreement);
router.get("/payments", listPayments);
router.post("/payments/preview", authorize("ADMIN","STAFF"), previewPayment);
router.post("/accounts/:id/payments/:paymentId/corrections/preview",authorize("ADMIN","STAFF"),correctPayment);
router.post("/payments", authorize("ADMIN", "STAFF"), acceptPayment);
router.get("/expenses", listExpenses);
router.post("/expenses", authorize("ADMIN", "STAFF"), createExpense);
router.get("/reports/monitoring.xlsx",exportMonitoringReport);
router.get("/reports/payment-register.xlsx",exportPaymentRegister);
router.get("/reports/dashboard",dashboardAnalytics);
router.get("/reports", report);
export default router;
